using System.Collections;
using System.Collections.Generic;

namespace xianze.math
{

    public class MyMath
    {
        public float Add(float a, float b)
        {
            float value = a + b;
            return value;
        }
        
        public float Add(float a, float b, float c, float d)
        {
            float value = a + b + c + d;
            return value;
        }
    }
}